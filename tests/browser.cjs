const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:8098';
const out = process.env.ARTIFACT_DIR || 'test-artifacts';
(async () => {
  await fs.mkdir(out, {recursive: true});
  const browser = await chromium.launch({headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? {executablePath: process.env.CHROMIUM_EXECUTABLE}: {})});
  const page = await browser.newPage({viewport: {width:1440,height:1000}});
  const errors=[]; page.on('pageerror', e => errors.push(e.message));
  let headers={}; page.on('request',async r => {if (r.url().includes('tce_show_result_user.php')) headers=await r.allHeaders()});
  const submit=async (selector) => Promise.all([page.waitForNavigation(),page.locator(selector).click()]);
  const login=async (area,user,password) => {
    // Preserve the upstream login rate limiter; separate simulated users in time.
    await new Promise(resolve=>setTimeout(resolve,4000));
    await page.context().clearCookies();
    await page.goto(`${base}/${area}/code/tce_login.php`);
    await page.locator('#xuser_name').fill(user);await page.locator('#xuser_password').fill(password);
    await submit('#login');await page.waitForURL('**/index.php').catch(async error=>{console.log((await page.locator('body').innerText()).slice(0,2200));throw error});assert.equal(await page.locator('#form_login').count(),0);
  };
  await page.goto(`${base}/public/code/`);
  assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
  await page.screenshot({path:`${out}/login.png`,fullPage:true});
  await login('public',process.env.TEST_STUDENT||'student','Student-Test-123!');
  let attempt=process.env.EXISTING_ATTEMPT;
  if (!attempt) {
    await page.goto(`${base}/public/code/tce_test_execute.php?testid=1`);
    attempt=await page.locator('#testuser_id').inputValue();
    assert.ok(Number(attempt)>0);
    await page.getByLabel('تهران',{exact:true}).check();
    await page.screenshot({path:`${out}/exam.png`,fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2),'Exam must fit mobile');
    await page.screenshot({path:`${out}/exam-mobile.png`,fullPage:true});
    await page.setViewportSize({width:1440,height:1000});
    await submit('#nextquestion');
    await page.getByLabel('۲',{exact:true}).check();await page.getByLabel('۴',{exact:true}).check();
    await submit('#nextquestion');
    await page.locator('#answertext').fill('یادگیری با تمرین و بررسی اشتباهات ادامه پیدا می‌کند.');
    await submit('#nextquestion');
    const order=page.locator('select[name^="answpos"]'); assert.equal(await order.count(),3);
    for(let i=0;i<3;i++) await order.nth(i).selectOption(String(i+1));
    await submit('#confirmanswer');await submit('#terminatetest');await submit('#forceterminate');
  }
  const result=`${base}/public/code/tce_show_result_user.php?test_id=1&testuser_id=${attempt}`;
  await page.goto(result);
  assert.equal(await page.locator('.az-score').count(),1);
  assert.equal(await page.locator('.az-metrics>div').count(),4);
  assert.ok(await page.locator('.az-selected').count()>=3);
  assert.ok(await page.locator('.az-answer-label').count()>=11);
  assert.ok((await page.locator('body').innerText()).includes('در انتظار تصحیح'));
  await page.screenshot({path:`${out}/results.png`,fullPage:true});
  const print=await page.pdf({path:`${out}/results-print.pdf`,format:'A4',printBackground:true});
  assert.equal(print.subarray(0,5).toString(),'%PDF-');
  await page.locator('.az-print').evaluate(el=>{window.__printed=false;window.print=()=>{window.__printed=true};el.click()});
  assert.equal(await page.evaluate(()=>window.__printed),true,'Print button invokes print');
  const href=await page.locator('a[href^="tce_pdf_results.php"]').getAttribute('href');
  const native=await page.request.get(new URL(href,page.url()).toString(),{headers});
  assert.equal(native.status(),200);const nativeBytes=await native.body();
  assert.equal(nativeBytes.subarray(0,5).toString(),'%PDF-');assert.ok(nativeBytes.length>10000);
  await fs.writeFile(`${out}/results-native.pdf`,nativeBytes);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2),'Results must fit mobile');
  await page.screenshot({path:`${out}/results-mobile.png`,fullPage:true});
  await page.goto(`${base}/admin/code/azmoon_settings.php`);
  assert.equal(await page.locator('#short_name').count(),0,'Student cannot change institution');
  await login('public',process.env.TEST_OTHER||'otherstudent','Student-Test-123!');
  await page.goto(result); assert.equal(await page.locator('.az-score').count(),0,'No other student results');
  const denied=await page.request.get(`${base}/public/code/tce_pdf_results.php?test_id=1&testuser_id=${attempt}&mode=3`,{headers:await page.evaluate(()=>({'User-Agent':navigator.userAgent,'Accept-Language':navigator.language}))});
  assert.notEqual((await denied.body()).subarray(0,5).toString(),'%PDF-','No other student PDF');
  // Log out via the same browser before administrator authentication.
  await login('admin',process.env.ADMIN_NAME||'manager',process.env.ADMIN_PASSWORD||'Test-Admin-Only-123!');
  await page.setViewportSize({width:1440,height:1000});await page.goto(`${base}/admin/code/`);
  await page.screenshot({path:`${out}/admin.png`,fullPage:true});
  await page.goto(`${base}/admin/code/azmoon_settings.php`);
  const original={short:await page.locator('#short_name').inputValue(),full:await page.locator('#full_name').inputValue(),color:await page.locator('#accent').inputValue()};
  // Invalid CSRF must leave the original identity intact.
  const csrf=await page.locator('[name="csrf_token"]').inputValue();
  await page.locator('[name="csrf_token"]').evaluate(el=>el.value='invalid');
  await submit('button[type="submit"]');assert.ok((await page.locator('body').innerText()).includes('درخواست معتبر نیست'));
  await page.goto(`${base}/admin/code/azmoon_settings.php`);
  assert.equal(await page.locator('#full_name').inputValue(),original.full);
  const brand="آموزشگاه «یادگیری» <نمونه> O'Neil";
  await page.locator('#short_name').fill('TEST');await page.locator('#full_name').fill(brand);
  await page.locator('#accent').fill('#0f766e');await submit('button[type="submit"]');
  assert.ok((await page.locator('.az-brand').innerText()).includes(brand));
  assert.equal(await page.locator('.az-brand نمونه').count(),0,'Identity remains escaped text');
  await page.screenshot({path:`${out}/settings.png`,fullPage:true});
  await page.locator('#short_name').fill(original.short);await page.locator('#full_name').fill(original.full);await page.locator('#accent').fill(original.color);await submit('button[type="submit"]');
  await page.goto(`${base}/admin/code/tce_edit_question.php`);
  await page.screenshot({path:`${out}/editor.png`,fullPage:true});
  assert.deepEqual(errors,[],'No browser script errors');
  await fs.writeFile(`${out}/report.json`,JSON.stringify({result:'PASS',engine:'latest stable',attempt,checks:['RTL','four question types','answer labels','essay pending','browser print','native PDF','mobile overflow','other user denied','student settings denied','CSRF','editable escaped identity','JavaScript errors']},null,2));
  console.log('PASS: exam, results, print/PDF, mobile, identity and access checks');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
